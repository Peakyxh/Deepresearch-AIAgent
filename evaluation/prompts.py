# ==================== Repeatability Evaluation ====================

REPEATABILITY_SYSTEM_PROMPT = """给定两个段落，请评估它们之间的内容重复程度。
你需要从多个角度进行分析，并根据评分标准给出合理的分数。

# 什么是"重复"：

观点或内容重复：两个段落表达了相同或高度相似的观点、主题或结论，无论是否进行了改写。
案例、数据或引用重复：使用了相同的案例、数据、事实或来源，或者对相同内容进行了改写或转述。
隐式重复：虽然措辞不同，但核心信息、论点或结论实质上相同。

# 什么不是"重复"：

表达方式差异：仅语言、句式或风格不同，但信息内容和核心观点并不相同。
主题相关但内容不同：主题相似，但传达的信息、论点或结论不同。
补充与延伸：一个段落是对另一个段落的补充、扩展或引入新观点，而非简单重复。

# 注意事项
关注内容：集中在信息层面的重复，而非仅看表面的语言或风格差异。
同时考虑显式和隐式重复：
显式重复：直接复制或近乎相同的文本。
隐式重复：通过改写、概括等方式表达相同信息。
考虑上下文影响：评估重复是否影响可读性和信息密度。
避免主观偏见：不要依赖个人知识或对内容正确性的判断，仅根据段落之间是否存在重复进行评分。

# 评分标准
使用0-4分制评估段落之间的重复程度：
4分（几乎无重复）：段落完全独立，没有重复的观点、案例或表达。
3分（轻微重复）：有1-2处轻微的内容重复，但不影响整体阅读体验。
2分（有一定重复）：有多处内容重复，在一定程度上影响阅读体验。
1分（严重重复）：大量内容重复，严重影响写作质量。
0分（过度重复）：几乎所有内容都重复，写作价值丧失。

# 重要提示：
- 请不要依赖你的外部知识；仅根据提供的内容进行判断
- 注意：使用相同的例子来解释不同的概念不算重复

# 一些可能有帮助的提示：
- 检查段落是否包含相同的引文
- 检查段落是否遵循相同的逻辑流程

# 输出格式
必须输出一个JSON对象，包含以下字段：

{
    "score": "基于上述标准的0-4分评分",
    "explanation": "评分解释，包含重复内容的具体示例",
    "repetitions_found": ["重复内容1", "重复内容2", "重复内容3", ...],
    "confidence": "评估置信度（0%-100%）"
}
"""

